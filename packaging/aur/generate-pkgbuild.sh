#!/usr/bin/env bash
# Prints the PKGBUILD for one of Lucent's AUR packages.
#
#   generate-pkgbuild.sh <lucent|lucent-bin> <version> <sha256> [pkgrel]
#
# <version> has no leading "v". <sha256> is the checksum of the release asset
# the package downloads: lucent-<version>.tar.gz (source) for `lucent`,
# lucent-<version>-x86_64.tar.gz (prebuilt) for `lucent-bin`.
# Generate .SRCINFO from the result with `makepkg --printsrcinfo`.
set -euo pipefail

usage() {
  echo "usage: $0 <lucent|lucent-bin> <version> <sha256> [pkgrel]" >&2
  exit 2
}

[[ $# -eq 3 || $# -eq 4 ]] || usage
pkg="$1" version="$2" sha256="$3" pkgrel="${4:-1}"

[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+([._+a-zA-Z0-9]*)$ ]] ||
  { echo "invalid version '$version' (expected e.g. 2.0.0, no leading v)" >&2; exit 2; }
[[ "$sha256" =~ ^[0-9a-f]{64}$ ]] ||
  { echo "invalid sha256 '$sha256'" >&2; exit 2; }
[[ "$pkgrel" =~ ^[1-9][0-9]*$ ]] ||
  { echo "invalid pkgrel '$pkgrel'" >&2; exit 2; }

url="${LUCENT_REPO_URL:-https://github.com/CPT-Dawn/Lucent}"

header() {
  cat <<EOF
# Maintainer: CPT-Dawn <dev@cptdawn.dev>
# Generated by packaging/aur/generate-pkgbuild.sh in ${url}; edit it there.
pkgname=$1
pkgver=${version}
pkgrel=${pkgrel}
pkgdesc="Fast, beautiful notification daemon for Wayland with history, Do Not Disturb and themes"
arch=($2)
url="${url}"
license=('MIT')
depends=('gcc-libs' 'glibc' 'glib2' 'gtk4' 'gtk4-layer-shell')
EOF
}

# Shared by both packages: the files the release tarballs ship, installed
# from the directory the tarball unpacks to.
package_body() {
  cat <<'EOF'
  install -Dm755 lucent -t "$pkgdir/usr/bin"
  install -Dm644 org.freedesktop.Notifications.service -t "$pkgdir/usr/share/dbus-1/services"
  install -Dm644 LICENSE -t "$pkgdir/usr/share/licenses/$pkgname"
  install -Dm644 README.md -t "$pkgdir/usr/share/doc/$pkgname"
EOF
}

case "$pkg" in
  lucent)
    header lucent "'x86_64' 'aarch64'"
    cat <<EOF
makedepends=('cargo')
conflicts=('lucent-bin')
source=("lucent-\$pkgver.tar.gz::\$url/releases/download/v\$pkgver/lucent-\$pkgver.tar.gz")
sha256sums=('${sha256}')

prepare() {
  cd "lucent-\$pkgver"
  export RUSTUP_TOOLCHAIN=stable
  cargo fetch --locked --target "\$(rustc -vV | sed -n 's/host: //p')"
}

build() {
  cd "lucent-\$pkgver"
  export RUSTUP_TOOLCHAIN=stable
  export CARGO_TARGET_DIR=target
  cargo build --frozen --release
}

check() {
  cd "lucent-\$pkgver"
  export RUSTUP_TOOLCHAIN=stable
  export CARGO_TARGET_DIR=target
  cargo test --frozen
}

package() {
  cd "lucent-\$pkgver"
  install -Dm755 target/release/lucent -t "\$pkgdir/usr/bin"
EOF
    package_body | sed '1d'
    echo "}"
    ;;
  lucent-bin)
    header lucent-bin "'x86_64'"
    cat <<EOF
provides=("lucent=\$pkgver")
conflicts=('lucent')
options=('!debug' '!strip')
source=("lucent-\$pkgver-x86_64.tar.gz::\$url/releases/download/v\$pkgver/lucent-\$pkgver-x86_64.tar.gz")
sha256sums=('${sha256}')

package() {
  cd "lucent-\$pkgver-x86_64"
EOF
    package_body
    echo "}"
    ;;
  *)
    echo "unknown package '$pkg' (expected lucent or lucent-bin)" >&2
    exit 2
    ;;
esac
